// 3. Prevent duplicate IDs and merge
const existingIds = new Set(existingScholarships.map(s => s.id));
let addedCount = 0;

for (const s of newScholarships) {
  if (existingIds.has(s.id)) {
    console.warn(`Warning: Duplicate ID ${s.id} detected, updating existing.`);
    const idx = existingScholarships.findIndex(x => x.id === s.id);
    existingScholarships[idx] = s;
  } else {
    existingScholarships.push(s);
    existingIds.add(s.id);
    addedCount++;
  }
}

console.log(`Added ${addedCount} brand new scholarships. Total count now: ${existingScholarships.length}`);

